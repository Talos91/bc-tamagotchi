"""Table QR codes for presence check-in (docs/design/08-presence.md §3, 08b §5; P9: one static code per table).

    python docs/venue/qr/make_qr.py            # (re)draw the sheet from codes.json; new tables get new codes
    python docs/venue/qr/make_qr.py --rotate Table3   # reprint one table: new code (deactivate the old one in SQL)

Writes, next to this file: codes.json (table -> code, the record), png/<table>.png (one code each, 1200 px),
qr-sheet.png and qr-sheet.pdf (A4 portrait, 4 x 5 cards with label and URL), and
supabase/seed/venue_tables.sql (upsert of every code; run it in the project's SQL editor or via the connector).
"""
import json, os, secrets, string, sys
import qrcode
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
BASE = 'https://blackcabin.app/?t='
# The venue tables (layout.json ids and zones) + one code for the bar counter. Card presence-qr-tables confirms.
TABLES = [
    ('Table0', 'Tables'), ('Table1', 'Tables'), ('Table2', 'Tables'), ('Table3', 'Tables'), ('Table4', 'Tables'),
    ('WestTable0', 'Tables'), ('WestTable1', 'Tables'), ('RectTableW', 'Tables'), ('RectTableE', 'Tables'),
    ('EastTable', 'Tables'), ('OpeningTall0', 'Tables'), ('OpeningTall1', 'Tables'),
    ('LongTable', 'Lounge'), ('LoungeTable0', 'Lounge'), ('LoungeTable1', 'Lounge'),
    ('BufferTall0', 'Buffer'), ('BufferTall1', 'Buffer'), ('BufferTall2', 'Buffer'), ('BufferTall3', 'Buffer'),
    ('Bar', 'Bar'),
]
ALPHABET = ''.join(c for c in string.ascii_letters + string.digits if c not in 'O0Il1')


def label(t):
    if t == 'Bar':
        return 'Bar counter'
    for a, b in (('RectTableW', 'Long table W'), ('RectTableE', 'Long table E'), ('LongTable', 'Lounge long table'),
                 ('EastTable', 'East table'), ('WestTable', 'West table '), ('LoungeTable', 'Lounge table '),
                 ('BufferTall', 'Tall table B'), ('OpeningTall', 'Tall table O'), ('Table', 'Table ')):
        if t.startswith(a):
            return (b + t[len(a):]).strip()
    return t


def new_code():
    return ''.join(secrets.choice(ALPHABET) for _ in range(10))


def font(size):
    for f in ('C:/Windows/Fonts/segoeuib.ttf', 'C:/Windows/Fonts/arialbd.ttf', 'DejaVuSans-Bold.ttf'):
        try:
            return ImageFont.truetype(f, size)
        except OSError:
            pass
    return ImageFont.load_default()


def qr_img(url, px):
    q = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, box_size=10, border=2)
    q.add_data(url)
    q.make(fit=True)
    return q.make_image(fill_color='black', back_color='white').convert('RGB').resize((px, px), Image.NEAREST)


def main():
    path = os.path.join(HERE, 'codes.json')
    codes = json.load(open(path, encoding='utf-8')) if os.path.exists(path) else {}
    if '--rotate' in sys.argv:
        t = sys.argv[sys.argv.index('--rotate') + 1]
        codes.pop(t, None)
    for t, _ in TABLES:
        if t not in codes:
            codes[t] = new_code()
    json.dump(codes, open(path, 'w', encoding='utf-8'), indent=2)

    os.makedirs(os.path.join(HERE, 'png'), exist_ok=True)
    for t, _ in TABLES:
        qr_img(BASE + codes[t], 1200).save(os.path.join(HERE, 'png', t + '.png'))

    # A4 at 150 dpi: 1240 x 1754; 4 columns x 5 rows of cards.
    W, H, cols, rows, m = 1240, 1754, 4, 5, 40
    cw, ch = (W - 2 * m) // cols, (H - 2 * m - 60) // rows
    sheet = Image.new('RGB', (W, H), 'white')
    d = ImageDraw.Draw(sheet)
    d.text((m, 18), 'Black Cabin - scan to check in (one code per table)', fill='black', font=font(30))
    f_lab, f_url = font(24), font(13)
    for i, (t, zone) in enumerate(TABLES):
        x, y = m + (i % cols) * cw, m + 60 + (i // cols) * ch
        d.rectangle([x + 4, y + 4, x + cw - 4, y + ch - 4], outline='#999999', width=2)
        q = qr_img(BASE + codes[t], min(cw, ch) - 80)
        sheet.paste(q, (x + (cw - q.width) // 2, y + 12))
        d.text((x + cw // 2, y + ch - 52), label(t), fill='black', font=f_lab, anchor='mm')
        d.text((x + cw // 2, y + ch - 24), t + ' - ' + codes[t], fill='#555555', font=f_url, anchor='mm')
    sheet.save(os.path.join(HERE, 'qr-sheet.png'))
    sheet.save(os.path.join(HERE, 'qr-sheet.pdf'), resolution=150.0)

    seed = os.path.join(ROOT, 'supabase', 'seed', 'venue_tables.sql')
    os.makedirs(os.path.dirname(seed), exist_ok=True)
    lines = ['-- Generated by docs/venue/qr/make_qr.py: one active code per table (P9). Old codes of a table go inactive.',
             'insert into public.venue_tables (code, table_id, label, zone, active) values']
    lines.append(',\n'.join("  ('%s', '%s', '%s', '%s', true)" % (codes[t], t, label(t), z) for t, z in TABLES))
    lines[-1] += '\non conflict (code) do update set table_id = excluded.table_id, label = excluded.label,'
    lines.append('  zone = excluded.zone, active = true;')
    lines.append('update public.venue_tables set active = false where code not in (%s);' %
                 ', '.join("'%s'" % codes[t] for t, _ in TABLES))
    open(seed, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print('codes:', len(TABLES), '-> qr-sheet.png/pdf, png/, supabase/seed/venue_tables.sql')


if __name__ == '__main__':
    main()
