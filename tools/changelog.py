"""Regenerate docs/CHANGELOG.md from git history, grouped under version headings. Run from the repo root:
    python tools/changelog.py
Each entry of RELEASES closes a version at its last commit (inclusive). Everything after the last one goes under the
version now in game/project.godot (`application/config/version`) as "(in progress)". To cut a version: append
(version, last_sha) here, bump the version in project.godot, rerun. docs/tech/versioning.md."""
import subprocess, io, collections, re

# (version, last commit of that version, inclusive), oldest first
RELEASES = [
    ('0.1.0', '51603f0'),
]

PREAMBLE = ['# Changelog', '', 'Every commit on `main`, grouped by game version, newest first (days newest first inside each),',
            'regenerated by the orchestrator with `python tools/changelog.py`. The version lives in',
            '`game/project.godot`; how versions are cut: `docs/tech/versioning.md`. Design decisions live in',
            '`docs/design/DECISIONS.md`; parity stats per iteration in `docs/art/parity-measurements.md`; what each wave',
            'delivered in `ORCHESTRATION.md`.', '']


def git(*args):
    return subprocess.run(['git'] + list(args), capture_output=True, text=True, encoding='utf-8').stdout


def current_version():
    m = re.search(r'^config/version="([^"]+)"', io.open('game/project.godot', encoding='utf-8').read(), re.M)
    return m.group(1) if m else '?'


log = [l.split('|', 3) for l in git('log', '--reverse', '--date=short', '--format=%H|%ad|%h|%s').splitlines()]
# groups[i] = commits of version i (RELEASES order, then the version in progress)
groups = [[] for _ in range(len(RELEASES) + 1)]
cuts = [git('rev-parse', sha).strip() for _, sha in RELEASES]
i = 0
for full, d, h, s in log:
    groups[i].append((d, h, s))
    if i < len(cuts) and full == cuts[i]:
        i += 1
titles = [v for v, _ in RELEASES] + [current_version() + ' (in progress)']
out = list(PREAMBLE)
for title, commits in reversed(list(zip(titles, groups))):
    if not commits:
        continue
    days = collections.OrderedDict()
    for d, h, s in commits:
        days.setdefault(d, []).append((h, s))
    out += ['## ' + title, '']
    for d in reversed(list(days)):
        out += ['### ' + d, ''] + ['- `%s` %s' % (h, s) for h, s in days[d]] + ['']
io.open('docs/CHANGELOG.md', 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print(len(log), 'commits;', ', '.join('%s: %d' % (t, len(g)) for t, g in zip(titles, groups)))
