"""Regenerate docs/CHANGELOG.md from git history. Run from the repo root: python tools/changelog.py"""
import subprocess, io, collections
log = subprocess.run(['git','log','--reverse','--date=short','--format=%ad|%h|%s'], capture_output=True, text=True, encoding='utf-8').stdout
days = collections.OrderedDict()
for line in log.splitlines():
    d, h, s = line.split('|', 2); days.setdefault(d, []).append((h, s))
out = ['# Changelog', '', 'Every commit on `main`, newest day first, regenerated by the orchestrator with',
       '`python tools/changelog.py`. Design decisions live in `docs/design/DECISIONS.md`; parity stats per',
       'iteration in `docs/art/parity-measurements.md`; what each wave delivered in `ORCHESTRATION.md`.', '']
for d in reversed(list(days)):
    out += ['## ' + d, ''] + ['- `%s` %s' % (h, s) for h, s in days[d]] + ['']
io.open('docs/CHANGELOG.md', 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print(len(days), 'days', sum(len(v) for v in days.values()), 'commits')
